#!/usr/bin/env python3
"""
Regenerate js/checklist-data.js from data/Photo_Checklist_Build_Out.xlsx.

Spreadsheet layout (Sheet1):
  Columns A-E  : selection categories (header in row 1, options below)
  Column G     : generic items that ALWAYS apply
  Columns H-AD : one column per option; header = option name, items below

Usage:
  pip install openpyxl
  python scripts/build_data.py [path/to/workbook.xlsx]
"""
import json
import re
import sys
from pathlib import Path

import openpyxl
from openpyxl.utils import column_index_from_string

ROOT = Path(__file__).resolve().parent.parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "data" / "Photo_Checklist_Build_Out.xlsx"
OUT = ROOT / "js" / "checklist-data.js"

CATEGORY_COLS = ["A", "B", "C", "D", "E"]
GENERIC_COL = "G"
FIRST_ITEM_COL, LAST_ITEM_COL = "H", "AD"

# Fix spelling in category headings for display only
HEADING_FIXES = {"Secondary Antena Type": "Secondary Antenna Type"}


def clean(v):
    if v is None:
        return None
    s = re.sub(r"[ \t]+", " ", str(v)).strip()
    s = "\n".join(line.strip() for line in s.splitlines())
    return s or None


def norm(s):
    return re.sub(r"[^a-z0-9]", "", s.lower())


def column_values(ws, col):
    idx = column_index_from_string(col)
    vals = []
    for row in range(2, ws.max_row + 1):
        v = clean(ws.cell(row=row, column=idx).value)
        if v:
            vals.append(v)
    return vals


def main():
    wb = openpyxl.load_workbook(SRC, data_only=True)
    ws = wb.worksheets[0]

    # Item columns H..AD keyed by header
    item_cols = {}
    for c in range(column_index_from_string(FIRST_ITEM_COL), column_index_from_string(LAST_ITEM_COL) + 1):
        header = clean(ws.cell(row=1, column=c).value)
        if header:
            item_cols[header] = [v for v in (clean(ws.cell(row=r, column=c).value) for r in range(2, ws.max_row + 1)) if v]

    def find_items(option):
        """Match an option (col A-E) to its item column header (H-AD)."""
        n = norm(option)
        for h in item_cols:  # exact
            if norm(h) == n:
                return h
        for h in item_cols:  # header with extra suffix, e.g. 'HG72710LP' -> 'HG72710LP (LTE)'
            if norm(h).startswith(n) or n.startswith(norm(h)):
                return h
        return None

    categories, warnings, used = [], [], set()
    for col in CATEGORY_COLS:
        heading = clean(ws[f"{col}1"].value)
        heading = HEADING_FIXES.get(heading, heading)
        options = []
        for opt in column_values(ws, col):
            h = find_items(opt)
            if not h:
                warnings.append(f"No item column found for '{opt}' ({heading})")
            else:
                used.add(h)
            options.append({"name": h or opt, "items": item_cols.get(h, [])})
        categories.append({"id": col, "name": heading, "options": options})

    for h in item_cols:
        if h not in used:
            warnings.append(f"Item column '{h}' is not linked to any option in columns A-E")

    data = {
        "source": SRC.name,
        "generic": {"name": clean(ws[f"{GENERIC_COL}1"].value), "items": column_values(ws, GENERIC_COL)},
        "categories": categories,
    }

    OUT.write_text(
        "// AUTO-GENERATED by scripts/build_data.py from data/" + SRC.name + " - do not edit by hand.\n"
        "window.CHECKLIST_DATA = " + json.dumps(data, indent=2, ensure_ascii=False) + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(data['generic']['items'])} generic items, "
          f"{sum(len(c['options']) for c in categories)} options")
    for w in warnings:
        print("WARNING:", w)


if __name__ == "__main__":
    main()
